HAND_DESIGN = ["crd", "rcbd", "split"]


def generated():
    import exp_designs as D
    rng = np.random.default_rng(20261117)
    items = []
    for fn, n in D.PLAN:
        for _ in range(n):
            items.append(fn(rng))
    order = np.random.default_rng(20261118).permutation(len(items))
    return [items[k] for k in order]


def build():
    from exp_designs import NOERR
    rng = np.random.default_rng(20261116)
    out = []
    src = [dict(e, design=HAND_DESIGN[i]) for i, e in enumerate(EXPS)] + generated()
    for i, e in enumerate(src):
        qs = []
        for q in e["qs"]:
            if q["t"] == "mc":
                opts = [q["correct"]] + q["wrongs"]
                order = list(rng.permutation(4))
                qs.append(dict(t="mc", q=q["q"], o=[opts[k] for k in order], a=order.index(0), ex=q["ex"]))
            elif q["t"] == "multi":
                if q["opts"][-1][0] == NOERR:
                    order = list(rng.permutation(len(q["opts"]) - 1)) + [len(q["opts"]) - 1]
                else:
                    order = list(rng.permutation(len(q["opts"])))
                opts = [q["opts"][k] for k in order]
                qs.append(dict(t="multi", q=q["q"], o=[o[0] for o in opts], a=[j for j, o in enumerate(opts) if o[1]], ex=q["ex"]))
            else:
                qs.append(dict(t="num", q=q["q"], a=q["a"], tol=q["tol"], ex=q["ex"], unit=""))
        lt = lambda t: t.replace("< ", "&lt; ")
        for q in qs:
            q["ex"] = lt(q["ex"])
            if "o" in q:
                q["o"] = [lt(o) for o in q["o"]]
        out.append(dict(id=i + 1, d=e["design"], title=e["title"], topic=e["topic"], story=lt(e["story"]), scheme=e["scheme"], qs=qs))
    return out


def pack(data):
    """Repeated strings go to a shared table S; in the data they are replaced by their index (the app decodes them)."""
    from collections import Counter
    cnt = Counter()
    for e in data:
        for q in e["qs"]:
            cnt[q["q"]] += 1
            cnt[q["ex"]] += 1
            for o in q.get("o", []):
                cnt[o] += 1
        cnt[e["title"]] += 1
        cnt[e["topic"]] += 1
    S = [t for t, n in cnt.items() if n > 1 and len(t) > 6]
    ix = {t: i for i, t in enumerate(S)}
    f = lambda t: ix.get(t, t)
    X = []
    for e in data:
        e = dict(e, title=f(e["title"]), topic=f(e["topic"]))
        e["qs"] = [dict(q, q=f(q["q"]), ex=f(q["ex"]), **({"o": [f(o) for o in q["o"]]} if "o" in q else {})) for q in e["qs"]]
        X.append(e)
    return dict(S=S, X=X)


if __name__ == "__main__":
    data = build()
    json.dump(pack(data), open("expdata.json", "w"), ensure_ascii=False, separators=(",", ":"))
    json.dump(data, open("/tmp/expdata_full.json", "w"), ensure_ascii=False, separators=(",", ":"))
    print(len(data), "experiments")
