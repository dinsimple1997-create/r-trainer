EXPS = []


def X(title, topic, story, scheme, qs):
    EXPS.append(dict(title=title, topic=topic, story=story, scheme=scheme, qs=qs))


def mc(q, correct, wrongs, ex):
    return dict(t="mc", q=q, correct=correct, wrongs=wrongs, ex=ex)


def multi(q, opts, ex):
    """opts: [(text, is_error)]"""
    return dict(t="multi", q=q, opts=opts, ex=ex)


def num(q, a, ex, tol=0):
    return dict(t="num", q=q, a=a, tol=tol, ex=ex, unit="")


def grid(rooms):
    """rooms: [(room label, [pen treatment codes])] -> data for a simple pen layout picture."""
    return rooms


