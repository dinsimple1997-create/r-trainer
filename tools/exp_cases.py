def mcq(rng, q, right, wrong, ex):
    wrong = [w for w in dict.fromkeys(wrong) if w != right][:3]
    opts = [right] + wrong
    order = list(rng.permutation(len(opts)))
    return dict(t="mc", q=q, o=[opts[i] for i in order], a=order.index(0), ex=ex)


def mq(rng, q, items, ex):
    order = list(rng.permutation(len(items)))
    return dict(t="multi", q=q, o=[items[i][0] for i in order], a=sorted(j for j, i in enumerate(order) if items[i][1]), ex=ex)


def nq(q, a, ex, tol=0.0):
    return dict(t="num", q=q, a=float(f"{a:.6g}"), tol=float(f"{tol:.4g}"), ex=ex, unit="")


def ru(x, d=2):
    s = f"{x:.{d}f}"
    if float(s) == 0:
        s = s.lstrip("-")
    return s.replace(".", ",").replace("-", "−")


def rua(x, sig=3):
    if x == 0:
        return "0"
    d = max(0, min(6, sig - 1 - math.floor(math.log10(abs(x)))))
    return ru(x, d)


def C(s):
    return f"<code>{s}</code>"


def pick(rng, qs, keep):
    """keep the first question, take `keep` - 1 of the rest in random order (variety between cases)."""
    rest = qs[1:]
    idx = sorted(rng.choice(len(rest), size=min(keep - 1, len(rest)), replace=False))
    return [qs[0]] + [rest[i] for i in idx]


