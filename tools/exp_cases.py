def choose_cases(rng, n):
    for i in range(n):
        s, right, wrong, unit, ex = CHOOSE[i % len(CHOOSE)]
        units = ["свинья", "загон", "комната", "свиноматка", "ферма", "поросёнок", "свиноматка (станок)", "свиноматка × период", "комната для обогрева, загон для рациона"]
        qs = [mcq(rng, "Какой анализ подходит?", C(right), [C(w) for w in wrong], ex),
              mcq(rng, "Что здесь единица эксперимента (или наблюдения, если опыта нет)?", unit, [u for u in units if u != unit][:6][int(rng.integers(0, 3)):][:3], "Единица — то, чему назначали вариант (или что наблюдали независимо).")]
        case("какой анализ", "Выбери анализ", f"<p>{s}</p>", qs)


