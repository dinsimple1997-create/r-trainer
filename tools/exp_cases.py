# 6. how many animals
def size_cases(rng, n):
    kinds = ["means", "deff", "detect", "props"]
    for i in range(n):
        k = kinds[i % 4]
        if k == "means":
            sd = float(rng.choice([25, 30, 35, 40, 45, 50]))
            dl = float(rng.choice([15, 20, 25, 30, 40]))
            nn = solve_n(dl, sd)
            appr = 2 * (1.96 + 0.8416) ** 2 * sd ** 2 / dl ** 2
            story = f"<p>Планируем опыт с рационом на загонах. SD среднего привеса загонов по прошлым партиям — {int(sd)} г/сут. Важная разница — {int(dl)} г/сут. α = 0,05, мощность 80%.</p>"
            nn2 = solve_n(dl, sd * 0.7)
            qs = [nq("Сколько загонов нужно на рацион? (округли вверх)", math.ceil(nn),
                     f"Формула: 2·(1,96 + 0,84)²·SD²/Δ² = {rua(appr, 3)}; power.t.test(delta = {int(dl)}, sd = {int(sd)}, power = 0.8) даёт n = {rua(nn, 4)} → <b>{math.ceil(nn)}</b>.", tol=1.01),
                  mcq(rng, "Как изменится n, если важная разница вдвое меньше?", "Вырастет примерно в 4 раза", ["Вырастет вдвое", "Не изменится", "Уменьшится вдвое"], "n ∝ 1/Δ²."),
                  nq("Блоки уменьшили SD на 30%. Сколько загонов теперь? (округли вверх)", math.ceil(nn2), f"SD = {rua(sd * 0.7, 3)} → n = {rua(nn2, 4)} → <b>{math.ceil(nn2)}</b>.", tol=1.01),
                  mcq(rng, "Какой SD правильно брать?", "SD средних загонов: загон — единица эксперимента", ["SD отдельных свиней", "SD всей фермы за год", "SD из учебника"],
                      "Разброс единиц эксперимента определяет точность.")]
            case("сколько животных", f"Мощность: Δ = {int(dl)}, SD = {int(sd)}", story, pick(rng, qs, 3))
        elif k == "deff":
            m = int(rng.choice([8, 10, 12, 15, 20, 25]))
            icc = float(rng.choice([0.05, 0.08, 0.1, 0.15, 0.2, 0.3]))
            pens = int(rng.choice([10, 12, 16, 20, 24]))
            de = 1 + (m - 1) * icc
            story = f"<p>{pens} загонов по {m} свиней. ICC привеса внутри загона по прошлым данным — {ru(icc, 2)}.</p>"
            qs = [nq("Design effect?", de, f"1 + ({m} − 1) × {ru(icc, 2)} = <b>{rua(de, 3)}</b>.", tol=0.02),
                  nq("Эффективное число «независимых свиней»?", pens * m / de, f"{pens * m} / {rua(de, 3)} = <b>{rua(pens * m / de, 3)}</b>.", tol=max(0.5, pens * m / de * 0.02)),
                  mcq(rng, "Что выгоднее добавить при том же числе свиней?", "Больше загонов с меньшим числом свиней", ["Больше свиней в те же загоны", "Одинаково", "Больше взвешиваний"],
                      "При ICC &gt; 0 каждая следующая свинья в загоне добавляет всё меньше информации.")]
            case("сколько животных", f"Design effect: {m} свиней в загоне", story, qs)
        elif k == "detect":
            p = float(rng.choice([0.02, 0.05, 0.1, 0.15, 0.2, 0.3]))
            se = float(rng.choice([1.0, 0.95, 0.9, 0.8]))
            nn = math.log(0.05) / math.log(1 - p * se)
            story = f"<p>Мониторинг стада: хотим с уверенностью 95% найти хотя бы одну положительную свинью, если распространённость не ниже {ru(100 * p, 0)}%. Чувствительность теста {ru(100 * se, 0)}%. Стадо большое.</p>"
            qs = [nq("Сколько свиней обследовать? (округли вверх)", math.ceil(nn), f"n = ln(0,05) / ln(1 − p·Se) = ln(0,05) / ln(1 − {ru(p * se, 3)}) = {rua(nn, 4)} → <b>{math.ceil(nn)}</b>.", tol=1.01),
                  mcq(rng, "Все результаты отрицательные. Вывод?", f"С уверенностью ~95% распространённость ниже {ru(100 * p, 0)}% (если болезнь вообще есть)",
                      ["Стадо свободно от болезни", "Тест не работает", "Нужно повторить с другим тестом"], "Выборка ограничивает распространённость сверху, но не доказывает ноль."),
                  mcq(rng, "Как отбирать свиней?", "Понемногу из многих загонов и секций", ["Всех из одного загона — проще", "Самых здоровых на вид", "Только из первой секции"],
                      "Болезни кластеризуются. Случайная выборка по всему стаду (лучше с упором на группы риска) отвечает на вопрос о стаде.")]
            case("сколько животных", f"Найти болезнь: p = {ru(100 * p, 0)}%", story, qs)
        else:
            p1 = float(rng.choice([0.06, 0.08, 0.10, 0.12]))
            p2 = p1 / float(rng.choice([1.5, 2.0]))
            pb = (p1 + p2) / 2
            nn = (1.959964 * math.sqrt(2 * pb * (1 - pb)) + 0.841621 * math.sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2 / (p1 - p2) ** 2
            story = f"<p>Хотим показать, что вакцина снижает падёж с {ru(100 * p1, 0)}% до {ru(100 * p2, 0)}%. Поросята — независимые единицы (индивидуальная рандомизация), α = 0,05, мощность 80%.</p>"
            qs = [nq("Сколько поросят на группу? (округли вверх)", math.ceil(nn),
                     f"power.prop.test(p1 = {p1}, p2 = {rua(p2, 3).replace(',', '.')}, power = 0.8) → n ≈ {rua(nn, 4)} → <b>{math.ceil(nn)}</b>. Редкий исход требует много животных.", tol=max(2, nn * 0.02)),
                  mcq(rng, "Если рандомизировать загоны по 25 поросят, а не поросят?", "Нужно больше поросят: надо умножить на design effect",
                      ["Столько же", "Меньше: загоны точнее", "Можно не считать"], "Падёж в загоне кластеризуется (общая инфекция), поэтому n × DE."),
                  mcq(rng, "Что в R?", C(f"power.prop.test(p1 = {p1}, p2 = {rua(p2, 3).replace(',', '.')}, power = 0.8)"),
                      [C(f"power.t.test(delta = {rua(p1 - p2, 3).replace(',', '.')}, power = 0.8)"), C("chisq.test(c(p1, p2))"), C("prop.test(p1, p2)")],
                      "Для двух долей — power.prop.test.")]
            case("сколько животных", f"Две доли: {ru(100 * p1, 0)}% → {ru(100 * p2, 0)}%", story, qs)


