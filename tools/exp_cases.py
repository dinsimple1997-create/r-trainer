def measure_cases(rng, n):
    designs = ["trial", "cohort", "cc", "xs"]
    for i in range(n):
        dz = designs[i % 4]
        if dz in ("trial", "cohort"):
            n1, n2 = int(rng.integers(80, 300)), int(rng.integers(80, 300))
            p1, p2 = rng.uniform(0.15, 0.35), rng.uniform(0.04, 0.14)
            a, c_ = int(round(n1 * p2)), int(round(n2 * p1))
            b, d = n1 - a, n2 - c_
