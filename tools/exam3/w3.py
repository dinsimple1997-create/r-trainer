def chart_quad():
    rng = np.random.default_rng(91)
    k = 32
    T = np.round(rng.uniform(15, 29, k), 1)
    adg = np.round(-400 + 110 * T - 2.5 * T ** 2 + rng.normal(0, 28, k))
    p = Plot((14.5, 29.5), (620, 900), xlab='температура в комнате, °C', ylab='привес, г/сут', title='Привес и температура: горб, а не прямая')
    p.points(T, adg)
    xs = np.linspace(14.5, 29.5, 80)
    p.line(xs, Q['b0'] + Q['b1'] * xs + Q['b2'] * xs ** 2)
    p.line([14.5, 29.5], [814.521 - 1.770 * 14.5, 814.521 - 1.770 * 29.5], color='var(--axis)', width=1.4, dash='6 4')
    p.seg(Q['xmax'], 620, Q['xmax'], 812.6, color='var(--series-2)', dash='3 3')
    p.text(Q['xmax'], 640, 'оптимум 22,4 °C', dx=6, cls='val')
    p.text(15.3, 848, 'пунктир — прямая: «нет связи»', color='var(--muted)')
    return figure([p.render('квадратичная')], '32 комнаты откорма. Прямая (серый пунктир) почти горизонтальна: p = 0,41, «температура не важна». Парабола показывает, что важна, и ещё как: и холод, и жара снижают привес, максимум около 22 °C.')


