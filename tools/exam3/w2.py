def chart_logit():
    rng = np.random.default_rng(41)
    n4 = 400
    wt = np.round(rng.uniform(3.5, 9.0, n4), 1)
    p = 1 / (1 + np.exp(-(1.6 - 0.62 * wt)))
    died = rng.binomial(1, p)
    pl = Plot((3.4, 9.1), (-0.08, 1.08), xlab='масса при отъёме, кг', ylab='пал (1) / жив (0)', title='Падёж отъёмышей: S-кривая', yticks=[0, 0.25, 0.5, 0.75, 1])
    jit = rng.uniform(-0.035, 0.035, n4)
    pl.points(wt, died + jit, r=2.0, op=0.35)
    xs = np.linspace(3.4, 9.1, 80)
    pl.line(xs, 1 / (1 + np.exp(-(L['b0'] + L['b1'] * xs))))
    pl.line([3.4, 9.1], [0.505, -0.2], color='var(--warn)', width=1.4, dash='5 4')
    pl.text(4.0, 0.29, 'P = 0,28 при 4 кг', dx=6, dy=-16, cls='val')
    pl.text(7.0, 0.07, 'P = 0,07 при 7 кг', dx=4, dy=-10, cls='val')
    pl.text(8.95, 0.5, 'пунктир — обычная прямая:', color='var(--warn)', anchor='end')
    pl.text(8.95, 0.5, 'уходит ниже нуля', color='var(--warn)', anchor='end', dy=15)
    return figure([pl.render('логистическая кривая')], 'Точки — 400 отъёмышей (1 — пал, 0 — выжил), чуть раздвинуты по вертикали, чтобы было видно. Оранжевая S-кривая — вероятность падежа из логистической модели: она всегда между 0 и 1. Пунктир — что было бы с обычной прямой: она уходит ниже нуля.')


