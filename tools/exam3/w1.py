def chart_slr():
    p = Plot((4.4, 8.6), (18, 38), xlab='масса при отъёме, кг', ylab='масса в 70 дней, кг', title='30 поросят: прямая R')
    p.points(pig.wean, pig.w70)
    xs = np.array([4.4, 8.6])
    p.line(xs, S['b0'] + S['b1'] * xs)
    # one residual
    i = int(np.argmax(pig.w70 - (S['b0'] + S['b1'] * pig.wean)))
    x, y = pig.wean[i], pig.w70[i]
    yh = S['b0'] + S['b1'] * x
    p.seg(x, yh, x, y, color='var(--warn)', width=2, dash='none')
    p.text(x, (y + yh) / 2, f'остаток e = +{ru(y-yh,1)} кг', dx=-6, anchor='end')
    p.text(6.0, S['b0'] + S['b1'] * 6.0, 'Ŷ = 11,56 + 2,46·X', dx=8, dy=22, cls='val')
    return figure([p.render('Точки и прямая регрессии')], 'Каждая точка — поросёнок. Оранжевая прямая — то, что посчитал R. Вертикальный отрезок — остаток: насколько поросёнок тяжелее (+) или легче (−), чем обещает прямая.')


