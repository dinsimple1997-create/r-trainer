def resid_panels():
    rng = np.random.default_rng(5)
    x = np.linspace(0, 10, 50)
    pans = []
    specs = [('Всё в порядке', rng.normal(0, 1, 50), 'ровная полоса вокруг 0'),
             ('Изгиб: нет линейности', 0.18 * (x - 5) ** 2 - 1.5 + rng.normal(0, 0.6, 50), 'подкова: нужна кривая или log'),
             ('Воронка: разная дисперсия', rng.normal(0, 1, 50) * (0.2 + 0.25 * x), 'разброс растёт: часто лечит log(Y)'),
             ('Выброс', np.r_[rng.normal(0, 1, 49), 5.2], 'одна точка далеко: проверить данные')]
    for title, r, note in specs:
        p = Plot((0, 10), (-6, 6), w=300, h=200, xlab='прогноз Ŷ', ylab='остаток', title=title, ml=40, mb=38, xticks=[], yticks=[-4, 0, 4])
        p.hline(0)
        p.points(x, r, r=2.6)
        p.text(0.2, -5.2, note)
        pans.append(p.render(title))
    return f'<figure><div class="grid2">{"".join(f"<div>{s}</div>" for s in pans)}</div><figcaption>График «остатки против прогноза» (residuals vs fitted). Читают его глазами: ищут изгиб, воронку и одиночные точки.</figcaption></figure>\n'


