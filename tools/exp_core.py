def num_ru(x, d=2):
    s = f"{x:.{d}f}".replace(".", ",")
    return s.replace("-", "−")


def p_ru(p):
    if p < 0.001:
        return "p < 0,001"
    if p < 0.01:
        return "p = " + f"{p:.4f}".replace(".", ",")
    return "p = " + f"{p:.3f}".replace(".", ",")


def t_report(p, df):
    t = stats.t.isf(p / 2, df)
    return f"t = {num_ru(t)}, df = {df}, {p_ru(p)}"


def f_report(p, df1, df2):
    f = stats.f.isf(p, df1, df2)
    return f"F({df1}, {df2}) = {num_ru(f)}, {p_ru(p)}"


def evidence(p):
    if p < 0.001:
        return "очень сильные доказательства"
    if p < 0.01:
        return "сильные доказательства"
    if p < 0.05:
        return "умеренные доказательства"
    if p < 0.10:
        return "слабые, наводящие доказательства"
    return "доказательств нет"


