def _order(rng, n):
    pos = np.tile(np.arange(4), n // 4 + 1)[:n]
    rng.shuffle(pos)  # balanced position of the right answer
    out = []
    for i in range(n):
        w = list(rng.permutation(3) + 1)
        out.append(w[:pos[i]] + [0] + w[pos[i]:])
    return out


